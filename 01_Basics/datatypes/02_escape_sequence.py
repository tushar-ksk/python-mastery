# \n make a new line
a = "tushar is a good boy \nbut not bad boy"
print(a)

b = 'tushar is a good boy "but" not a bad boy'
print(b)



# \t make a gap of tab
c = "tushar is a good boy\tbut not bad boy"
print(c)


# we use \"xyz\" to print"xyz"
d = "tushar is a good boy \"but\" not bad boy"
print(d)
